import React from 'react';
import assert from 'node:assert/strict';
import {renderToStaticMarkup} from 'react-dom/server';
import {MemoryRouter} from 'react-router-dom';
import {Invitation} from '../src/Invitation';
import {Admin} from '../src/Admin';
import {defaults} from '../src/data';
import {eventInstant,localDateValue,validateInvitation} from '../src/configTools';
import {parseGuestCSV,prepareGuestImport} from '../src/csvTools';
import {GeneralContent,SectionSettings,AppearanceSettings,EventDateField,ReadinessChecklist} from '../src/EditorSettings';
import {verifyAdminAccess,AdminAuthClient} from '../src/adminAccess';

const memory=new Map<string,string>();
const storage={getItem:(k:string)=>memory.get(k)??null,setItem:(k:string,v:string)=>memory.set(k,v),removeItem:(k:string)=>memory.delete(k)};
Object.assign(globalThis,{localStorage:storage,sessionStorage:storage});
const render=(element:React.ReactNode)=>renderToStaticMarkup(<MemoryRouter>{element}</MemoryRouter>);
storage.setItem('blessing-open-v2','yes');
const cover=render(<Invitation c={defaults}/>);
assert.match(cover,/envelope-flap/);
assert.match(cover,/letter-border/);
assert.match(cover,/Open Invitation/);
assert.match(cover,/satin-bow.png/);
assert.ok(!cover.includes('Main navigation'),'The website stays hidden until the envelope opens, even on a return visit.');
assert.ok(!cover.includes('Will you be attending'),'RSVP content must not appear behind the sealed envelope.');
const invitation=render(<Invitation c={defaults} preview/>);
assert.match(invitation,/christening-portrait.png/);
assert.ok(invitation.includes(defaults.rsvpTitle??'Will you be attending')); 
assert.match(invitation,/The Ceremony/);
assert.match(invitation,/Gallery/);
assert.ok(!invitation.includes('<footer'),'The public invitation has no bottom footer.');
assert.ok(!invitation.includes('Admin Panel'),'Administration must not be advertised on the public invitation.');
const admin=render(<Admin config={defaults} onPublish={()=>{}}/>);
assert.match(admin,/Admin Sign In/);
assert.match(admin,/Admin access is locked/);
for(const label of ['Hero Section','Live Preview','Save Changes','RSVP Responses'])assert.ok(!admin.includes(label),`Unauthenticated admin exposes ${label}`);
let roleQueries=0;
const fakeClient=(user:boolean,role:string|null,authError=false,roleError=false)=>({
  auth:{getUser:async()=>({data:{user:user?{id:'verified-user'}:null},error:authError?Error('Invalid token'):null})},
  from:()=>{roleQueries++;return {select:()=>({eq:()=>({maybeSingle:async()=>({data:role?{role}:null,error:roleError?Error('Unavailable'):null})})})}}
}) as unknown as AdminAuthClient;
assert.equal(await verifyAdminAccess(null),'unavailable');
assert.equal(await verifyAdminAccess(fakeClient(false,null)),'signed-out');
assert.equal(await verifyAdminAccess(fakeClient(true,'owner',true)),'signed-out');
assert.equal(roleQueries,0,'Invalid sessions must not query private role data');
assert.equal(await verifyAdminAccess(fakeClient(true,null)),'forbidden');
assert.equal(await verifyAdminAccess(fakeClient(true,'viewer')),'forbidden');
assert.equal(await verifyAdminAccess(fakeClient(true,'admin')),'authorized');
assert.equal(await verifyAdminAccess(fakeClient(true,'owner')),'authorized');
assert.equal(await verifyAdminAccess(fakeClient(true,'admin',false,true)),'error');
console.log('PASS: envelope and invitation render; footer removed; admin is locked without verified identity and an admin/owner role.');

const customized={...defaults,name:'Isabella Rose',invitationTitle:'Baptism',dedication:'of our beloved daughter',eventHeading:'Our celebration',galleryHeading:'Precious memories',closingHeading:'From our family',welcome:'A personal welcome',rsvpButton:'Send our reply',sections:['message','details'] as const};
const customHTML=render(<Invitation c={{...customized,sections:[...customized.sections]}} preview/>);
for(const text of ['Isabella Rose','Baptism','of our beloved daughter','Our celebration','From our family'])assert.ok(customHTML.includes(text),'Configured content missing: '+text);
assert.ok(!customHTML.includes('id="gallery"'),'Hidden gallery must not render');
assert.ok(!customHTML.includes('RSVP Now'),'Hidden RSVP must remove every RSVP button');
assert.ok(customHTML.indexOf('From our family')<customHTML.indexOf('Our celebration'),'Configured section order must be honored');
assert.ok(!invitation.includes('/photo-1.jpg')&&!invitation.includes('/photo-2.jpg'),'Mismatched old sample photos must not be used');
const update=()=>{};
for(const element of [<GeneralContent c={defaults} update={update}/>,<SectionSettings c={defaults} update={update}/>,<AppearanceSettings c={defaults} update={update}/>,<ReadinessChecklist c={defaults} guests={0} navigate={()=>{}}/>,<EventDateField label="Event" value="2027-03-15T02:00:00Z" timezone="not-a-zone" onChange={()=>{}}/>])assert.ok(render(element).length>0);
assert.equal(eventInstant('2027-03-15T10:00','Asia/Manila'),'2027-03-15T02:00:00.000Z');
assert.equal(localDateValue('2027-03-15T02:00:00Z','Asia/Manila'),'2027-03-15T10:00');
assert.equal(eventInstant('2027-03-15T00:15','Asia/Manila'),'2027-03-14T16:15:00.000Z');
assert.throws(()=>eventInstant('2027-03-14T02:30','America/New_York'));
assert.throws(()=>eventInstant('2027-02-30T10:00','Asia/Manila'));
assert.ok(validateInvitation(defaults,true).some(message=>message.includes('event date')));
assert.ok(validateInvitation({...defaults,date:'2027-03-15T02:00:00Z',deadline:'2027-03-16T02:00:00Z'}).some(message=>message.includes('deadline')));
console.log('PASS: content wiring, section visibility/order, editor controls, safe publish validation, timezone conversion and invalid-time handling.');

const parsed=parseGuestCSV('group_name,guest_full_name\r\nSantos,"Santos, Maria"\r\nSantos,Jose Santos\r\n,Juan Cruz');
assert.equal(parsed.rows[0][1],'Santos, Maria');
let id=0;
const prepared=prepareGuestImport(parsed,{name:'guest_full_name',group:'group_name',key:'',status:''},[],()=>String(++id));
assert.equal(prepared.issues.length,0);assert.equal(prepared.groups.length,2);assert.equal(prepared.groups[0].members.length,2);
const separate=prepareGuestImport(parseGuestCSV('name\nMaria Santos\nJose Santos'),{name:'name',group:'',key:'',status:''},[],()=>String(++id));
assert.equal(separate.groups.length,2,'Surnames must not infer family membership');
assert.throws(()=>parseGuestCSV('name\n"unclosed'));
assert.throws(()=>parseGuestCSV('name\nSantos,Maria'));
assert.throws(()=>parseGuestCSV('name,name\nA,B'));
const duplicate=prepareGuestImport(parseGuestCSV('name\nMaria Santos\nMaria Santos'),{name:'name',group:'',key:'',status:''},[],()=>String(++id));
assert.equal(duplicate.duplicateCandidates,1);assert.equal(duplicate.groups.length,2,'Duplicate names must retain distinct invitations');
console.log('PASS: quoted CSV values, explicit family grouping, duplicate review, and malformed-file handling.');
